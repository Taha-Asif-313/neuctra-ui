import fs from "fs-extra";
import path from "path";
import { addNamedImport, backupOnce, insertImport } from "./fs-utils.js";
import { getThemeScript, SCRIPT_MARKER, DEFAULT_STORAGE_KEY } from "./theme-script.js";

// Storage key used by the ThemeContext files that CLI versions <= 0.1.x
// generated. Kept for migrated apps so returning visitors keep their choice.
const LEGACY_STORAGE_KEY = "theme";

const firstExisting = async (dir, names) => {
  for (const name of names) {
    const full = path.join(dir, name);
    if (await fs.pathExists(full)) return full;
  }
  return null;
};

// ---------------------------------------------------------------------------
// Legacy ThemeContext (generated by older CLI versions)
// ---------------------------------------------------------------------------

const legacyCompat = (ts) => `"use client";

// Kept by @neuctra/ui-cli so existing imports of "./contexts/ThemeContext" keep
// working. The theme now comes from @neuctra/ui; storageKey "theme" preserves
// the preference saved by the previous version of this file.
import { ThemeProvider as NeuctraThemeProvider, useTheme } from "@neuctra/ui";
${ts ? 'import type { ThemeProviderProps } from "@neuctra/ui";\n' : ""}
export function ThemeProvider(props${ts ? ": ThemeProviderProps" : ""}) {
  return <NeuctraThemeProvider storageKey="${LEGACY_STORAGE_KEY}" {...props} />;
}

export { useTheme };
`;

/**
 * Finds a ThemeContext file written by an older CLI. If it is still the
 * untouched generated template, it is replaced by a thin wrapper around the
 * library's ThemeProvider (the old file read localStorage during render, which
 * caused hydration mismatches, and its context did not match ThemeToggleButton).
 */
const migrateLegacyContext = async (cwd, changes, manual) => {
  for (const dir of ["src/contexts", "app/contexts", "src/app/contexts", "contexts"]) {
    const file = await firstExisting(path.join(cwd, dir), ["ThemeContext.tsx", "ThemeContext.jsx", "ThemeContext.ts", "ThemeContext.js"]);
    if (!file) continue;
    const content = await fs.readFile(file, "utf8");
    if (content.includes('from "@neuctra/ui"')) return { file, storageKey: LEGACY_STORAGE_KEY };
    const generated = content.includes("createContext") && content.includes('localStorage.getItem("theme")') && content.includes("toggleTheme");
    if (!generated) {
      manual.push(`${path.relative(cwd, file)} is a custom theme context. It was left as is; make sure it toggles the "dark" class on <html>, or switch to ThemeProvider from @neuctra/ui.`);
      return { file, storageKey: LEGACY_STORAGE_KEY, custom: true };
    }
    const backup = await backupOnce(file);
    await fs.writeFile(file, legacyCompat(/\.tsx?$/.test(file)));
    changes.push(`Migrated ${path.relative(cwd, file)} to the @neuctra/ui ThemeProvider (backup: ${path.basename(backup)})`);
    return { file, storageKey: LEGACY_STORAGE_KEY };
  }
  return null;
};

// ---------------------------------------------------------------------------
// JSX helpers
// ---------------------------------------------------------------------------

const scriptJsx = (storageKey) =>
  `<script id="${SCRIPT_MARKER}" dangerouslySetInnerHTML={{ __html: ${JSON.stringify(getThemeScript({ storageKey }))} }} />`;

/** Adds suppressHydrationWarning to <html> and the theme script to <head>. */
const addHeadScript = (content, storageKey) => {
  let next = content;
  next = next.replace(/<html\b([^>]*)>/, (match, attrs) => {
    if (attrs.includes("suppressHydrationWarning")) return match;
    if (!attrs.includes("\n")) return `<html${attrs} suppressHydrationWarning>`;
    // Multi-line tag: add the attribute on its own line with the same indent.
    const trailing = attrs.match(/\s*$/)[0];
    const indent = (attrs.match(/\n([ \t]*)\S[^\n]*\s*$/) ?? [, "      "])[1];
    return `<html${attrs.slice(0, attrs.length - trailing.length)}\n${indent}suppressHydrationWarning${trailing}>`;
  });
  if (next.includes(SCRIPT_MARKER)) return next;
  if (/<head\b[^>]*>/.test(next)) {
    return next.replace(/<head\b[^>]*>/, (open) => `${open}\n        ${scriptJsx(storageKey)}`);
  }
  if (/<head\s*\/>/.test(next)) {
    return next.replace(/<head\s*\/>/, `<head>\n        ${scriptJsx(storageKey)}\n      </head>`);
  }
  return next.replace(/<html\b[^>]*>/, (open) => `${open}\n      <head>\n        ${scriptJsx(storageKey)}\n      </head>`);
};

/** Index just past the ")" matching the "(" at `openIndex` (strings and JSX braces respected). */
const matchParen = (text, openIndex) => {
  let depth = 0;
  for (let i = openIndex; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === '"' || ch === "'" || ch === "`") {
      const quote = ch;
      i += 1;
      while (i < text.length && text[i] !== quote) i += text[i] === "\\" ? 2 : 1;
      continue;
    }
    if (ch === "(") depth += 1;
    else if (ch === ")") {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
};

/**
 * The storage key the theme script must read: the legacy key only when the
 * file that provides the theme imports the migrated ./contexts/ThemeContext
 * wrapper, otherwise the @neuctra/ui default.
 */
const storageKeyFor = (content, legacy) =>
  legacy && !legacy.custom && /from\s*["'][^"']*contexts\/ThemeContext["']/.test(content)
    ? legacy.storageKey
    : DEFAULT_STORAGE_KEY;

const PROVIDERS_OPEN = "<ThemeProvider>\n      <ToastProvider>";
const PROVIDERS_CLOSE = "</ToastProvider>\n    </ThemeProvider>";

/** Wraps a Vite entry's render tree once: inside <StrictMode> when present, else the render() argument. */
const wrapViteRender = (content) => {
  const strict = content.match(/<(React\.)?StrictMode>([\s\S]*?)<\/(React\.)?StrictMode>/);
  if (strict) {
    const [whole, prefix = "", inner] = strict;
    const tag = `${prefix}StrictMode`;
    return content.replace(whole, `<${tag}>\n    ${PROVIDERS_OPEN}\n        ${inner.trim()}\n      ${PROVIDERS_CLOSE}\n  </${tag}>`);
  }
  const call = content.search(/\.render\s*\(/);
  if (call === -1) return null;
  const open = content.indexOf("(", call);
  const close = matchParen(content, open);
  if (close === -1) return null;
  const arg = content.slice(open + 1, close).trim().replace(/,\s*$/, "");
  if (!arg.startsWith("<")) return null;
  return `${content.slice(0, open + 1)}\n  ${PROVIDERS_OPEN}\n      ${arg}\n    ${PROVIDERS_CLOSE}\n${content.slice(close)}`;
};

