const providersFile = (ts) => `"use client";

${ts ? 'import type { ReactNode } from "react";\n' : ""}import { ThemeProvider, ToastProvider } from "@neuctra/ui";

export function Providers({ children }${ts ? ": { children: ReactNode }" : ""}) {
  return (
    <ThemeProvider>
      <ToastProvider>{children}</ToastProvider>
    </ThemeProvider>
  );
}
`;

const setupNext = async ({ cwd, entryFile, language, legacy, changes, manual }) => {
  if (!entryFile) {
    manual.push("Next.js App Router layout (app/layout.tsx) not found. Wrap your app in <ThemeProvider> and <ToastProvider> from @neuctra/ui.");
    return;
  }
  const appDir = path.dirname(entryFile);
  const providersPath = await firstExisting(appDir, ["providers.tsx", "providers.jsx", "providers.js", "providers.ts"]);
  let storageKey = DEFAULT_STORAGE_KEY;

  if (!providersPath) {
    const file = path.join(appDir, `providers.${language === "ts" ? "tsx" : "jsx"}`);
    await fs.writeFile(file, providersFile(language === "ts"));
    changes.push(`Created ${path.relative(cwd, file)} (ThemeProvider + ToastProvider)`);
  } else {
    const content = await fs.readFile(providersPath, "utf8");
    storageKey = storageKeyFor(content, legacy);
    if (!content.includes("ThemeProvider")) {
      manual.push(`${path.relative(cwd, providersPath)} exists without ThemeProvider. Wrap its children in <ThemeProvider><ToastProvider>…</ToastProvider></ThemeProvider> from @neuctra/ui.`);
    }
  }

  let layout = await fs.readFile(entryFile, "utf8");
  const before = layout;
  if (!layout.includes("<Providers")) {
    const body = /(<body\b[^>]*>)([\s\S]*?)(<\/body>)/;
    if (body.test(layout)) {
      layout = layout.replace(body, (_, open, children, close) => `${open}\n        <Providers>${children.trim()}</Providers>\n      ${close}`);
      layout = insertImport(layout, 'import { Providers } from "./providers";', (c) => /import\s*\{\s*Providers\s*\}/.test(c));
    } else {
      manual.push(`Could not find <body> in ${path.relative(cwd, entryFile)}. Wrap {children} in <Providers> from "./providers".`);
    }
  }
  layout = addHeadScript(layout, storageKey);
  if (layout !== before) {
    await backupOnce(entryFile);
    await fs.writeFile(entryFile, layout);
    changes.push(`Updated ${path.relative(cwd, entryFile)} (Providers, no-flash theme script, suppressHydrationWarning)`);
  }
};

const setupVite = async ({ cwd, entryFile, legacy, changes, manual }) => {
  let storageKey = DEFAULT_STORAGE_KEY;
  if (!entryFile) {
    manual.push("No src/main entry file found. Wrap your app in <ThemeProvider> and <ToastProvider> from @neuctra/ui.");
  } else {
    let content = await fs.readFile(entryFile, "utf8");
    if (content.includes("<ThemeProvider")) {
      // Already wrapped (possibly by an older CLI); only ensure ToastProvider is imported.
    } else {
      const wrapped = wrapViteRender(content);
      if (!wrapped) {
        manual.push(`Could not find the render call in ${path.relative(cwd, entryFile)}. Wrap <App /> in <ThemeProvider><ToastProvider>…</ToastProvider></ThemeProvider> from @neuctra/ui.`);
      } else {
        content = wrapped;
        const source = legacy && !legacy.custom ? null : "@neuctra/ui";
        content = addNamedImport(content, "ToastProvider", "@neuctra/ui");
        if (source) content = addNamedImport(content, "ThemeProvider", source);
        else {
          let spec = path.relative(path.dirname(entryFile), legacy.file).split(path.sep).join("/").replace(/\.(t|j)sx?$/, "");
          if (!spec.startsWith(".")) spec = `./${spec}`;
          content = insertImport(content, `import { ThemeProvider } from "${spec}";`, (c) => /import\s*\{[^}]*ThemeProvider[^}]*\}/.test(c));
        }
        await backupOnce(entryFile);
        await fs.writeFile(entryFile, content);
        changes.push(`Wrapped the app in ThemeProvider + ToastProvider in ${path.relative(cwd, entryFile)}`);
      }
    }
    storageKey = storageKeyFor(content, legacy);
  }

  const html = path.join(cwd, "index.html");
  if (await fs.pathExists(html)) {
    const content = await fs.readFile(html, "utf8");
    if (!content.includes(SCRIPT_MARKER) && /<head\b[^>]*>/.test(content)) {
      const tag = `<script id="${SCRIPT_MARKER}">${getThemeScript({ storageKey })}</script>`;
      await fs.writeFile(html, content.replace(/<head\b[^>]*>/, (open) => `${open}\n    ${tag}`));
      changes.push("Added the no-flash theme script to index.html");
    }
  }
};

const setupRouteRoot = async ({ cwd, entryFile, framework, legacy, changes, manual }) => {
  if (!entryFile) {
    manual.push(`${framework} root route (app/root.tsx) not found. Wrap <Outlet /> in <ThemeProvider> and <ToastProvider> from @neuctra/ui.`);
    return;
  }
  let content = await fs.readFile(entryFile, "utf8");
  const before = content;
  if (!content.includes("<ThemeProvider")) {
    const bareReturn = content.match(/return\s+(<Outlet\s*\/>|<Outlet\s*><\/Outlet>)\s*;?/);
    const outlet = content.match(/<Outlet\s*\/>|<Outlet\s*><\/Outlet>/);
    if (bareReturn) {
      content = content.replace(bareReturn[0], `return (\n    <ThemeProvider>\n      <ToastProvider>\n        ${bareReturn[1]}\n      </ToastProvider>\n    </ThemeProvider>\n  );`);
    } else if (outlet) {
      content = content.replace(outlet[0], `<ThemeProvider>\n      <ToastProvider>\n        ${outlet[0]}\n      </ToastProvider>\n    </ThemeProvider>`);
    }
    if (bareReturn || outlet) {
      content = addNamedImport(content, "ThemeProvider", "@neuctra/ui");
      content = addNamedImport(content, "ToastProvider", "@neuctra/ui");
    } else {
      manual.push(`Could not find <Outlet /> in ${path.relative(cwd, entryFile)}. Wrap it in <ThemeProvider> and <ToastProvider> from @neuctra/ui.`);
    }
  }
  if (/<html\b/.test(content)) content = addHeadScript(content, storageKeyFor(content, legacy));
  else manual.push(`No <html> element in ${path.relative(cwd, entryFile)}; add the theme script from getThemeScript() (@neuctra/ui) to your document <head> to avoid a theme flash.`);
  if (content !== before) {
    await backupOnce(entryFile);
    await fs.writeFile(entryFile, content);
    changes.push(`Updated ${path.relative(cwd, entryFile)} (ThemeProvider + ToastProvider, no-flash theme script)`);
  }
};

export const setupFramework = async ({ cwd, framework, language = "js", entryFile }) => {
  const changes = [];
  const manual = [];
  const legacy = await migrateLegacyContext(cwd, changes, manual);
  if (framework === "next") await setupNext({ cwd, entryFile, language, legacy, changes, manual });
  else if (framework === "vite") await setupVite({ cwd, entryFile, legacy, changes, manual });
  else await setupRouteRoot({ cwd, entryFile, framework, legacy, changes, manual });
  return { changes, manual };
};
