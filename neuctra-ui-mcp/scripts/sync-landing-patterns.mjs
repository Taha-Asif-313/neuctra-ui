// Builds data/landing-patterns.json, the source code served by the
// neuctra-ui-landing-design tool. The tool has to work on Cloudflare Workers,
// which cannot read files at runtime, so the code ships as JSON. The real
// landing page stays the single source of truth; patterns/ holds the portable
// components that page does not use.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const site = path.resolve(root, "..", "neuctra-ui-docs-v2");
const fromSite = (file) => path.join(site, file);
const fromPatterns = (file) => path.join(root, "patterns", file);

const FOUNDATION = {
  "MotionPreference.jsx": fromSite("components/patterns/MotionPreference.js"),
  "useLoopingStages.js": fromSite("components/patterns/useLoopingStages.js"),
  "useScrub.js": fromSite("components/landing/useScrub.js"),
  "themeScope.js": fromSite("components/landing/themeScope.js"),
  "Reveal.jsx": fromSite("components/landing/Reveal.js"),
};

const SIGNATURES = {
  "assembly-hero": fromSite("components/landing/AssemblyHero.js"),
  untangle: fromSite("components/landing/UntangleSection.js"),
  "sideways-pipeline": fromSite("components/landing/PipelineSection.js"),
  "token-tree": fromSite("components/landing/LiveShowcase.js"),
  "audience-map": fromSite("components/landing/AudienceMap.js"),
  "finish-line-close": fromSite("components/landing/ClosingSection.js"),
  "scroll-statement": fromPatterns("ScrollReveal.jsx"),
  "hub-diagram": fromPatterns("HubDiagram.jsx"),
  "pinned-steps": fromPatterns("PinnedSteps.jsx"),
  "count-up-proof": fromPatterns("CountUp.jsx"),
};

const read = (file) => {
  if (!fs.existsSync(file)) {
    console.error(`Landing pattern source not found: ${file}`);
    process.exit(1);
  }
  return fs.readFileSync(file, "utf8");
};

const globalCss = read(fromSite("app/globals.css"));
const marker = "/* ── Landing page motion";
if (!globalCss.includes(marker)) {
  console.error(`Could not find "${marker}" in the site's globals.css`);
  process.exit(1);
}

const output = {
  $comment: "Generated by scripts/sync-landing-patterns.mjs. Do not edit by hand.",
  foundation: {
    files: Object.fromEntries(Object.entries(FOUNDATION).map(([name, file]) => [name, read(file)])),
    css: `body {\n  overflow-x: clip;\n}\n\n${globalCss.slice(globalCss.indexOf(marker)).trimEnd()}\n`,
    noscript:
      "<noscript><style>{`[data-reveal]{opacity:1!important;transform:none!important}[data-draw]{stroke-dasharray:none!important}[data-track]{overflow-x:auto}`}</style></noscript>",
  },
  signatures: Object.fromEntries(Object.entries(SIGNATURES).map(([id, file]) => [id, read(file)])),
};

const destination = path.join(root, "data", "landing-patterns.json");
fs.writeFileSync(destination, `${JSON.stringify(output, null, 2)}\n`);
console.log(`Synced landing patterns -> ${path.relative(process.cwd(), destination)}`);
